def area(a, h):
    '''
    Возвращает площадь треугольника по основанию и высоте.

    Параметры:
        a (float): длина основания треугольника, a >= 0
        h (float): высота, проведённая к основанию, h >= 0

    Возвращаемое значение:
        area (float): площадь треугольника, S = ah / 2

    Пример вызова:
        area(6, 4)  # вернёт 12.0
    '''
    return a * h / 2


def perimeter(a, b, c):
    '''
    Возвращает периметр треугольника по длинам его сторон.

    Параметры:
        a (float): длина первой стороны, a >= 0
        b (float): длина второй стороны, b >= 0
        c (float): длина третьей стороны, c >= 0

    Возвращаемое значение:
        perimeter (float): периметр треугольника, P = a + b + c

    Пример вызова:
        perimeter(3, 4, 5)  # вернёт 12
    '''
    return a + b + c